# Generates tests/pickle/float_literal_chain_main.pkl
#
# Companion to the emit_test.pkl oracle table. That table calls floatVal() with a
# hand-written string, so it proves floatVal parses correctly but never proves the
# LEXER hands floatVal the right text. This main closes that gap: every literal
# below is written as real source, so the full pipeline (lexer -> parser ->
# floatVal -> x64 -> runtime compare) runs, and GATE6 byte-diffs the Rust-compiled
# stdout against the port-compiled stdout.
#
# The literals are emitted in ascending value order, and each one is compared to
# its predecessor with `>` and `==`. That pair is maximally sensitive to a single
# corrupted constant: if any literal is misparsed, the chain ordering breaks and
# the two compilers disagree on that line. No expected values are baked in -- the
# Rust build is the oracle, which is what keeps this honest.
$ErrorActionPreference = 'Stop'
$out = "$env:TEMP\opencode\float_oracle"
$main = "tests\pickle\float_literal_chain_main.pkl"

$rows = @()
foreach ($ln in @(Get-Content "$out\float_oracle.tsv")) {
    $p = $ln -split "`t"
    if ($p.Count -lt 2 -or $p[1] -like 'ERR:*') { continue }
    # The pickle lexer rejects "1." with a syntax error, so it cannot appear as
    # source even though Rust's f64 parser accepts it. Verified by probing each
    # syntax form through `pickle-cli run`. floatVal still handles "1." correctly
    # and that case stays covered by the emit_test.pkl oracle table.
    if ($p[0] -eq '1.') { continue }
    $t = $p[0]
    # A digit-only token lexes as an integer, not a float. That is wrong twice
    # over here: it makes the chain compare int against float, and
    # 123456789012345678901234567890 overflows i64 outright. Appending ".0" keeps
    # the same f64 value while forcing the float path. The emit_test.pkl oracle
    # table still exercises the bare digit string, since floatVal is reached
    # there directly.
    if ($t -match '^-?[0-9]+$') { $t = "$t.0" }
    $rows += [pscustomobject]@{ Text = $t; Bits = [int64]$p[1] }
}
$n = $rows.Count
if ($n -lt 100) { throw "expected the full oracle table, got $n rows" }

$L = @()
foreach ($r in $rows) { $L += "    let L$($L.Count) = $($r.Text)" }

$P = @()
$P += 'module main'
$P += ''
$P += '// GENERATED by tools\gen_float_literal_chain_main.ps1. Do not hand-edit.'
$P += '//'
$P += '// Float-literal differential probe. The literals are in ascending value order'
$P += '// (ordered by the Rust oracle, so -0.0 precedes 0.0) and each is compared with'
$P += '// `>` and `==` against its predecessor.'
$P += '//'
$P += '// Rows are keyed by index rather than by value: printing a subnormal expands to'
$P += '// hundreds of digits and would bloat the goldens for no extra signal.'
$P += '//'
$P += '// Ties are expected and meaningful. Several texts legitimately parse to the same'
$P += '// f64 (the whole saturation tail is 0.0 or +/-inf, and 1e-324 underflows to 0.0),'
$P += '// so a `F` on the `>` column with a `T` on the `==` column is the correct'
$P += '// answer, not a failure.'
$P += '//'
$P += "// $n literals, covering the subnormal band, the subnormal/normal boundary, 2^53"
$P += '// and neighbours, long digit runs, both saturation tails, and syntax forms that'
$P += '// Rust accepts (".5", "1.", "1E5", "1e+5").'
$P += ''
$P += 'fn b(v: bool): string {'
$P += '    if (v) { "T" } else { "F" }'
$P += '}'
$P += ''
$P += 'fn main() {'
$P += $L
$P += "    println(`"L0 start`")"
for ($i = 1; $i -lt $n; $i++) {
    $P += "    println(`"L$i `", b(L$i > L$($i - 1)), b(L$i == L$($i - 1)))"
}
$P += '}'
$P += ''

Set-Content -Path $main -Value ($P -join "`n") -Encoding ASCII
"generated : $main"
"literals  : $n"
"lines     : $(@(Get-Content $main).Count)"
''
'--- first 3 + last 2 let lines ---'
$L | Select-Object -First 3 | ForEach-Object { "  $_" }
'  ...'
$L | Select-Object -Last 2 | ForEach-Object { "  $_" }
''
'--- first 2 + last 2 println lines ---'
$P | Where-Object { $_ -match 'println\("L' } | Select-Object -First 2 | ForEach-Object { "  $_" }
$P | Where-Object { $_ -match 'println\("L' } | Select-Object -Last 2 | ForEach-Object { "  $_" }