}

# Rebuild every oracle and port artifact this battery compares against. tools/diff/ is
# gitignored, so on a clean checkout GATE1/2/3/4/5 would compare against nothing and
# report 0 without saying why. Regenerating here rather than trusting pre-baked files
# also means a stale oracle can no longer mask a port regression. Prep skips fast when
